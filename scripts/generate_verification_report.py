"""Generate Stage B Verification Report from all test results.

Per the Stage B Verification Suite spec §1.11.
Collects results from all test runs + kill switch load test + coverage.
Produces docs/audits/stage-b-verification-report.md with GO/NO-GO verdict.
"""

import json
import argparse
from pathlib import Path
from datetime import datetime


def generate_report(output_path: str):
    """Generate Stage B verification report."""
    report = {
        "audit_id": "AUD-STAGE-B-001",
        "date": datetime.now().strftime("%Y-%m-%d"),
        "auditor": "CI/CD Pipeline (Stage B Verification)",
        "scope": "Phases 11-14 Stage B Verification",
        "verdict": "UNKNOWN",
        "gate_items": {},
    }

    verify_results = Path("verify-results")

    # ── Kill Switch <200ms SLO ─────────────────────────────────────
    ks_file = verify_results / "kill_switch_results.json"
    if ks_file.exists():
        with open(ks_file) as f:
            ks_results = json.load(f)
        slo_met = ks_results.get("results", {}).get("slo_met", False)
        p99 = ks_results.get("results", {}).get("p99_ms", 0)
        report["gate_items"]["kill_switch_200ms_slo"] = {
            "status": "PASS" if slo_met else "FAIL",
            "p99_ms": p99,
            "threshold_ms": 200,
            "disconnects": ks_results.get("results", {}).get("disconnects_recorded", 0),
        }
    else:
        report["gate_items"]["kill_switch_200ms_slo"] = {
            "status": "UNVERIFIED",
            "reason": "kill_switch_results.json not found",
        }

    # ── Coverage ───────────────────────────────────────────────────
    cov_file = Path("coverage.xml")
    if cov_file.exists():
        report["gate_items"]["coverage_measured"] = {
            "status": "PASS",
            "note": "Coverage report exists — check CI for per-module percentages",
        }
    else:
        report["gate_items"]["coverage_measured"] = {
            "status": "UNVERIFIED",
            "reason": "coverage.xml not found",
        }

    # ── Linter ─────────────────────────────────────────────────────
    report["gate_items"]["linter_rules_1_110"] = {
        "status": "UNVERIFIED",
        "reason": "Check CI linter step output",
    }

    # ── Concurrency Tests ──────────────────────────────────────────
    report["gate_items"]["phase_11_concurrency"] = {
        "status": "UNVERIFIED",
        "reason": "Check CI pytest tests/concurrency/ step output",
    }

    # ── Financial Audit Chain Tamper ───────────────────────────────
    report["gate_items"]["financial_audit_chain_tamper"] = {
        "status": "UNVERIFIED",
        "reason": "Check CI pytest tests/security/test_financial_audit_chain_tamper.py output",
    }

    # ── PCI DLP Injection ──────────────────────────────────────────
    report["gate_items"]["pci_dlp_injection"] = {
        "status": "UNVERIFIED",
        "reason": "Check CI pytest tests/security/test_pci_dlp_injection.py output",
    }

    # ── Cross-Module SE ────────────────────────────────────────────
    report["gate_items"]["cross_module_se_enforcement"] = {
        "status": "UNVERIFIED",
        "reason": "Check CI pytest tests/integration/test_cross_module_se_enforcement.py output",
    }

    # ── SE-survives-erasure ────────────────────────────────────────
    report["gate_items"]["se_survives_erasure"] = {
        "status": "UNVERIFIED",
        "reason": "Check CI pytest tests/integration/test_se_survives_erasure.py output",
    }

    # ── Determine verdict ──────────────────────────────────────────
    # Gate is GO only if Kill Switch SLO is PASS and no item is FAIL.
    ks_status = report["gate_items"].get("kill_switch_200ms_slo", {}).get("status", "UNVERIFIED")
    any_fail = any(
        item.get("status") == "FAIL"
        for item in report["gate_items"].values()
    )

    if ks_status == "PASS" and not any_fail:
        report["verdict"] = "CONDITIONAL-GO"
        # Full GO requires all items PASS (not just Kill Switch).
        all_pass = all(
            item.get("status") == "PASS"
            for item in report["gate_items"].values()
        )
        if all_pass:
            report["verdict"] = "GO"
    elif any_fail:
        report["verdict"] = "NO-GO"
    else:
        report["verdict"] = "UNVERIFIED"

    # ── Write report ───────────────────────────────────────────────
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        f.write(f"""---
audit_id: {report['audit_id']}
date: {report['date']}
auditor: {report['auditor']}
scope: {report['scope']}
verdict: {report['verdict']}
---

# Stage B Verification Report

## Verdict: {report['verdict']}

**Note:** This report is generated by CI/CD. Items marked UNVERIFIED
require manual review of CI step output. The verdict is CONDITIONAL-GO
if Kill Switch <200ms SLO is PASS and no items are FAIL. Full GO
requires all items PASS.

## Gate Items

""")
        for item_name, data in report["gate_items"].items():
            status = data.get("status", "UNKNOWN")
            icon = {"PASS": "✅", "FAIL": "❌", "UNVERIFIED": "⚠️"}.get(status, "❓")
            f.write(f"- {icon} **{item_name}**: {status}\n")
            for k, v in data.items():
                if k != "status":
                    f.write(f"  - {k}: {v}\n")
            f.write("\n")

        f.write(f"""
## Interpretation

| Verdict | Meaning |
|---|---|
| GO | All gate items PASS. Phase 15 may proceed. |
| CONDITIONAL-GO | Kill Switch SLO PASS; some items UNVERIFIED (check CI output). |
| NO-GO | At least one gate item FAIL. Phase 15 BLOCKED. |
| UNVERIFIED | Kill Switch SLO not measured. Phase 15 BLOCKED. |

## Next Steps

1. Review CI step outputs for all UNVERIFIED items.
2. If all PASS → Phase 15 may proceed.
3. If any FAIL → fix the failure → re-run `make verify-stage-b`.
4. Share this report + `verify-results/kill_switch_results.json` + coverage report with mentor.
""")

    print(f"\nVerification report generated: {output_path}")
    print(f"Verdict: {report['verdict']}")
    print(f"\nGate items:")
    for item_name, data in report["gate_items"].items():
        status = data.get("status", "UNKNOWN")
        print(f"  {item_name}: {status}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate Stage B Verification Report")
    parser.add_argument("--output", default="docs/audits/stage-b-verification-report.md",
                        help="Output file path")
    args = parser.parse_args()
    generate_report(args.output)
